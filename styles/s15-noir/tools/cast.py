def glasses_q(ey, r=15, col=BLACK, lens=None, glare=None, square=False, ear_x=58):
    s = []
    def one(cx, rx, ry):
        if square:
            pts = [(cx - rx, ey - ry * 0.75), (cx + rx, ey - ry * 0.85), (cx + rx * 0.9, ey + ry * 0.8), (cx - rx * 0.85, ey + ry * 0.8)]
        else:
            import math
            pts = [(cx + rx * math.cos(a / 8 * 6.2832), ey + 2 + ry * math.sin(a / 8 * 6.2832), 's') for a in range(8)]
        t = ''
        if lens:
            t += shape(pts, lens, 'fill-opacity="0.9"')
        if glare:
            t += clip(pts, shape([(cx - rx, ey + ry * 0.2), (cx + rx * 0.2, ey - ry), (cx + rx * 0.9, ey - ry), (cx - rx * 0.6, ey + ry)], glare))
        t += f'<path d="{d(pts)}" fill="none" stroke="{col}" stroke-width="2.6"/>'
        return t
    s.append(one(-50, r * 0.52, r * 0.95)); s.append(one(-6, r, r))
    s.append(line([(-41, ey - 2), (-34, ey - 5, 's'), (-22, ey - 2)], col, 2.6))
    s.append(line([(-6 + r, ey - 3), (ear_x, ey - 6)], col, 2.6))
    return ''.join(s)


